import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const output = new URL("../src/bokehforge/review/static/view-state.js", import.meta.url);
const notices = await Promise.all([
  ["serialize-query-params", "LICENSE"],
  ["valibot", "LICENSE.md"],
].map(async ([name, file]) => name + "\n" +
  (await readFile(new URL("node_modules/" + name + "/" + file, import.meta.url), "utf8")).trim()));
const result = await build({
  absWorkingDir: fileURLToPath(new URL(".", import.meta.url)),
  entryPoints: ["view-state.ts"],
  bundle: true,
  write: false,
  format: "esm",
  target: "es2022",
  minify: true,
  banner: { js: "/* Generated by npm run build in bokehforge/web.\n\n" + notices.join("\n\n") + "\n*/" },
});
const code = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (code !== await readFile(output, "utf8")) throw new Error("Run npm run build in bokehforge/web.");
} else {
  await writeFile(output, code);
}
